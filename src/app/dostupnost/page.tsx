import type { Metadata } from "next";
import { getLegalContacts, H2, LegalPage, LEGAL_EDITION, List } from "@/components/legal/legal-page";
import { t } from "@/i18n/ru";

// Заявление о доступности (решение 2 ноября 2026, раздел 9 ТЗ): израильские правила о доступности услуг (2013)
// ссылаются на стандарт IS 5568 (WCAG 2.0, уровень AA). Нужна ли сайту полная проверка — вопрос юристу.
export const metadata: Metadata = {
  title: "Заявление о доступности",
  description: `Как ${t.site.brand} обеспечивает доступность для людей с ограничениями и как сообщить о проблеме.`,
  alternates: { canonical: "/dostupnost" },
};

export default async function AccessibilityPage() {
  const c = await getLegalContacts();
  return (
    <LegalPage title="Заявление о доступности" current="/dostupnost">
      <p>
        Мы хотим, чтобы {t.site.brand} было удобно пользоваться всем, в том числе людям с нарушениями зрения, слуха и движения.
        Сайт делается с учётом израильского стандарта IS 5568, основанного на рекомендациях WCAG 2.0 уровня AA.
      </p>

      <H2>Что сделано</H2>
      <List>
        <li>Сайт работает с клавиатуры; первая ссылка на странице — «К содержимому», чтобы пропустить меню.</li>
        <li>Контраст текста и кнопок соответствует уровню AA; размер текста меняется настройками браузера без поломки страницы.</li>
        <li>Страницы перестраиваются под ширину экрана от 320 пикселей без горизонтальной прокрутки.</li>
        <li>У фото есть текстовые описания, у кнопок-значков — подписи для экранного диктора, у полей форм — названия.</li>
        <li>Адрес, часы работы, цены и контакты карточек даны текстом, а не картинками.</li>
        <li>Язык страниц указан в разметке, заголовки идут по порядку.</li>
      </List>

      <H2>Известные ограничения</H2>
      <List>
        <li>Карты (в каталоге и в карточках) неудобны для экранного диктора; те же адреса всегда есть текстом и в списке.</li>
        <li>Фото, видео и PDF-меню загружают владельцы карточек: у части из них может не быть описаний и субтитров.</li>
        <li>Встроенные карта Google и видео YouTube и Vimeo — внешние сервисы, их доступность зависит от этих компаний.</li>
      </List>

      <H2>Как сообщить о проблеме</H2>
      <p>
        Если что-то на сайте вам недоступно, напишите на {c.email}: какая страница, что не получилось и каким устройством или
        программой вы пользуетесь. Ответственный за доступность — {c.owner}. Мы ответим и постараемся исправить проблему как
        можно скорее.
      </p>
      <p className="text-sm text-muted">Заявление обновлено {LEGAL_EDITION}.</p>
    </LegalPage>
  );
}
